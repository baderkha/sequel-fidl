/* Run against a disposable PostgreSQL server: SEQUEL_POSTGRES_TEST_URL=... npm run test:postgres */
const assert = require('assert/strict');
const path = require('path');
const root = path.resolve(__dirname, '..');
process.env.NODE_PATH = [
    path.join(root, 'src'),
    path.join(root, 'release/app/node_modules'),
    process.env.NODE_PATH,
]
    .filter(Boolean)
    .join(path.delimiter);
require('module').Module._initPaths();
const { Sequelize, QueryTypes } = require(path.join(
    root,
    'release/app/node_modules/sequelize'
));
const {
    PostgresAdminCommand,
} = require('../src/main/util/sql_admin_commands/PostgresAdminCommand');
const { PostgresSource } = require('../src/main/service/export/PostgresSource');
const { POSTGRES_INTRO_SQL } = require('../src/main/service/postgresSample');
const { normalizeValue } = require('../src/main/service/export/columns');
const {
    ParquetSerializer,
} = require('../src/main/service/export/serializers/parquet');
const {
    buildPostgresSQL,
    buildPostgresAlter,
    postgresTableDef,
} = require('../src/renderer/Components/CreateTable/postgres');
const {
    newTable,
    newColumn,
} = require('../src/renderer/Components/CreateTable/model');
const url = process.env.SEQUEL_POSTGRES_TEST_URL;
if (!url)
    throw new Error(
        'Set SEQUEL_POSTGRES_TEST_URL to a disposable PostgreSQL server.'
    );
const con = new Sequelize(url, {
    logging: false,
    dialectModule: require(path.join(root, 'release/app/node_modules/pg')),
});
const admin = new PostgresAdminCommand();
const schema = `sequel_test_${Date.now()}`;
const q = (name) => `"${schema}"."${name}"`;
const name = (table) => `${schema}.${table}`;

(async () => {
    await con.authenticate();
    await con.query(`CREATE SCHEMA "${schema}"`);
    try {
        await con.transaction(async (transaction) => {
            await con.query(`SET LOCAL search_path TO "${schema}"`, {
                transaction,
            });
            await con.query(POSTGRES_INTRO_SQL, { transaction });
        });
        assert.equal(
            (await admin.ShowAllTables(con)).filter((t) =>
                t.Name.startsWith(schema + '.')
            ).length,
            6
        );
        assert.equal(
            (await admin.ShowSchema(con, name('books'))).find(
                (c) => c.FieldName === 'id'
            ).AutoIncrement,
            true
        );
        const metadata = await admin.GetTableMetadata(con, name('books'));
        assert.equal(metadata.foreignKeys[0].rt, name('authors'));
        assert.match(metadata.ddl, /GENERATED BY DEFAULT AS IDENTITY/);
        const [books, error] = await admin.SelectFromTable(con, {
            tableName: name('books'),
            limit: 10,
            offset: 0,
            orderByCol: 'title',
            extraFilters: [
                { Column: 'title', Operation: 'LIKE', Value: '%Earthsea%' },
            ],
        });
        assert.ifError(error);
        assert.equal(books.length, 1);
        assert.equal((await admin.CountRows(con, name('books'), []))[0], 5);
        const insertResult = await admin.InsertRows(
            con,
            name('books'),
            ['author_id', 'title', 'price', 'tags', 'details'],
            [
                [
                    1,
                    'Integration book',
                    '123456.78',
                    ['sample', 'test'],
                    '{"nested":{"ok":true}}',
                ],
            ]
        );
        assert.ifError(insertResult[1]);
        assert.equal(
            insertResult[0],
            1,
            'Successful inserts must report one affected row to Content'
        );
        const row = (
            await con.query(
                `SELECT * FROM ${q('books')} WHERE title='Integration book'`,
                { type: QueryTypes.SELECT }
            )
        )[0];
        assert.deepEqual(row.tags, ['sample', 'test']);
        assert.ifError(
            (
                await admin.UpdateRows(
                    con,
                    name('books'),
                    [{ column: 'title', mode: 'value', value: 'Updated book' }],
                    [{ id: row.id }],
                    false
                )
            )[1]
        );
        assert.equal(
            (
                await admin.DeleteRows(
                    con,
                    name('books'),
                    [{ id: row.id }],
                    false
                )
            )[0],
            1
        );
        const [conflictCount, conflictError] = await admin.InsertRows(
            con,
            name('customers'),
            ['name', 'email'],
            [['Copy', 'alex@example.test']],
            true
        );
        assert.ifError(conflictError);
        assert.equal(conflictCount, 0);
        const bulkResult = await admin.InsertRows(
            con,
            name('customers'),
            ['name', 'email'],
            [
                ['Insert test A', 'insert-a@example.test'],
                ['Insert test B', 'insert-b@example.test'],
            ]
        );
        assert.ifError(bulkResult[1]);
        assert.equal(bulkResult[0], 2);

        await con.query(
            `CREATE TABLE ${q(
                'duplicates'
            )}(value text, detail jsonb, tags text[]); INSERT INTO ${q(
                'duplicates'
            )} VALUES ('same','{"a":1}',ARRAY['x']),('same','{"a":1}',ARRAY['x'])`
        );
        const key = { value: 'same', detail: { a: 1 }, tags: ['x'] };
        assert.equal(
            (
                await admin.UpdateRows(
                    con,
                    name('duplicates'),
                    [{ column: 'value', mode: 'value', value: 'changed' }],
                    [key],
                    true
                )
            )[0],
            1
        );
        assert.equal(
            (await admin.DeleteRows(con, name('duplicates'), [key], true))[0],
            1
        );
        await con.query(
            `CREATE TABLE ${q('json_keys')}(value json); INSERT INTO ${q(
                'json_keys'
            )} VALUES ('"hello"'),('42'),('true'),('null')`
        );
        for (const value of ['hello', 42, true, null]) {
            const [n, error] = await admin.DeleteRows(
                con,
                name('json_keys'),
                [{ value }],
                true
            );
            assert.ifError(error);
            assert.equal(n, 1);
        }

        await con.transaction(async (transaction) => {
            const pendingInsert = await admin.InsertRows(
                con,
                name('books'),
                ['author_id', 'title', 'price'],
                [[1, 'Uncommitted book', 9.99]],
                false,
                transaction
            );
            assert.ifError(pendingInsert[1]);
            assert.equal(pendingInsert[0], 1);
            const failed = await admin.InsertRows(
                con,
                name('books'),
                ['author_id', 'title', 'price'],
                [[-1, 'Invalid foreign key', 9.99]],
                false,
                transaction
            );
            assert.ok(failed[1]);
            assert.ok(
                (
                    await admin.SelectFromTable(
                        con,
                        {
                            tableName: name('missing_table'),
                            limit: 1,
                            offset: 0,
                            extraFilters: [],
                        },
                        transaction
                    )
                )[1]
            );
            await assert.rejects(() =>
                new PostgresSource(
                    con,
                    `SELECT * FROM ${q('missing_table')}`,
                    [],
                    { transaction }
                ).open()
            );
            assert.equal(
                (
                    await admin.CountRows(
                        con,
                        name('books'),
                        [],
                        undefined,
                        transaction
                    )
                )[0],
                6
            );
            assert.equal(
                (await admin.ShowSchema(con, name('books'), transaction))
                    .length,
                7
            );
            const borrowed = await new PostgresSource(
                con,
                `SELECT title FROM ${q(
                    'books'
                )} WHERE title='Uncommitted book'`,
                [],
                { transaction, batchSize: 1 }
            ).open();
            let n = 0;
            for await (const batch of borrowed.batches) n += batch.length;
            assert.equal(n, 1);
            await borrowed.close();
            assert.equal(
                (
                    await admin.DeleteRows(
                        con,
                        name('books'),
                        [{ title: 'Uncommitted book' }],
                        false,
                        transaction
                    )
                )[0],
                1
            );
        });

        const source = new PostgresSource(
            con,
            `SELECT 9007199254740993::bigint AS big, 12345678901234567890.12345::numeric(30,5) AS exact, true AS enabled, '2026-01-01 12:34:56.123456+00'::timestamptz AS ts, ARRAY[1,2] AS numbers, '"true"'::jsonb AS json_string, decode('00ff','hex') AS bytes`,
            [],
            { batchSize: 1 }
        );
        const opened = await source.open();
        let rows = [];
        for await (const batch of opened.batches) rows.push(...batch);
        await opened.close();
        rows = rows.map((r) =>
            r.map((v, i) => normalizeValue(opened.columns[i].kind, v))
        );
        assert.equal(rows[0][0], 9007199254740993n);
        assert.equal(rows[0][1], '12345678901234567890.12345');
        assert.equal(rows[0][2], true);
        assert.equal(rows[0][3], '2026-01-01 12:34:56.123456');
        assert.deepEqual(rows[0][4], [1, 2]);
        assert.equal(rows[0][5], 'true');
        assert.deepEqual(rows[0][6], Buffer.from([0, 255]));
        const empty = await new PostgresSource(
            con,
            `SELECT * FROM ${q('books')} LIMIT 0`,
            []
        ).open();
        assert.equal(empty.columns.length, 7);
        await empty.close();
        const decimalTypes = await new PostgresSource(
            con,
            'SELECT 123.123456789012345678901234567890123456789::numeric unbounded, 12345::numeric(2,-3) rounded, 0.00123::numeric(3,5) fractional',
            []
        ).open();
        assert.equal(decimalTypes.columns[0].precision, undefined);
        assert.equal(decimalTypes.columns[1].precision, 5);
        assert.equal(decimalTypes.columns[1].scale, 0);
        assert.equal(decimalTypes.columns[2].precision, 5);
        assert.equal(decimalTypes.columns[2].scale, 5);
        const decimalRows = [];
        for await (const batch of decimalTypes.batches)
            decimalRows.push(...batch);
        await decimalTypes.close();
        const chunks = [];
        const writer = await new ParquetSerializer().open(
            decimalTypes.columns,
            { codec: 'UNCOMPRESSED' },
            {
                write: async (chunk) => {
                    chunks.push(Buffer.from(chunk));
                },
            }
        );
        await writer.writeRows(decimalRows);
        await writer.end();
        const { ParquetReader } = require(path.join(
            root,
            'release/app/node_modules/@dsnp/parquetjs'
        ));
        const reader = await ParquetReader.openBuffer(Buffer.concat(chunks));
        assert.equal(
            (await reader.getCursor().next()).unbounded,
            '123.123456789012345678901234567890123456789'
        );
        await reader.close();
        const bound = await new PostgresSource(
            con,
            `SELECT * FROM ${q('books')} WHERE title = ?`,
            ['A Wizard of Earthsea']
        ).open();
        for await (const batch of bound.batches)
            assert.equal(batch[0][2], 'A Wizard of Earthsea');
        await bound.close();
        const partial = await new PostgresSource(
            con,
            'SELECT generate_series(1,10000) n',
            [],
            { batchSize: 2 }
        ).open();
        await partial.close();
        await partial.close();

        const defaultsOnly = newTable('postgres');
        defaultsOnly.name = name('generated_ids');
        await con.query(buildPostgresSQL(defaultsOnly));
        const identitySequences = await con.query(
            'SELECT pg_get_serial_sequence(?, ?) AS name',
            {
                replacements: [q('generated_ids'), 'id'],
                type: QueryTypes.SELECT,
            }
        );
        assert.ok(
            identitySequences[0].name,
            'An identity must create an actual backing sequence'
        );
        const sequenceKind = await con.query(
            'SELECT relkind FROM pg_class WHERE oid=to_regclass(?)',
            { replacements: [identitySequences[0].name], type: QueryTypes.SELECT }
        );
        assert.equal(sequenceKind[0].relkind, 'S');
        assert.deepEqual(
            await admin.InsertRows(con, name('generated_ids'), [], [[]]),
            [1, null]
        );
        assert.deepEqual(
            await admin.InsertRows(con, name('generated_ids'), [], [[], []]),
            [2, null]
        );
        assert.deepEqual(
            (
                await con.query(
                    `SELECT id FROM ${q('generated_ids')} ORDER BY id`,
                    { type: QueryTypes.SELECT }
                )
            ).map((row) => row.id),
            [1, 2, 3]
        );
        const def = newTable('postgres');
        def.name = name('wizard');
        def.options.engine = '';
        def.columns = [
            newColumn({
                name: 'id',
                type: 'INTEGER',
                param: '',
                primaryKey: true,
                autoIncrement: true,
            }),
            newColumn({ name: 'label', type: 'TEXT', param: '' }),
        ];
        await con.query(buildPostgresSQL(def));
        const original = postgresTableDef(
            await admin.GetTableMetadata(con, name('wizard')),
            name('wizard')
        );
        const edited = JSON.parse(JSON.stringify(original));
        edited.columns.find((c) => c.name === 'label').name = 'description';
        edited.columns.push(
            newColumn({
                name: 'active',
                type: 'BOOLEAN',
                param: '',
                defaultMode: 'expression',
                defaultValue: 'true',
            })
        );
        await con.transaction(async (transaction) => {
            for (const sql of buildPostgresAlter(original, edited))
                await con.query(sql, { transaction });
        });
        assert.ok(
            (await admin.ShowSchema(con, name('wizard'))).some(
                (c) => c.FieldName === 'description'
            )
        );
        assert.ifError(
            await admin.CloneTable(con, name('books'), name('books_copy'), true)
        );
        assert.equal(
            (await admin.CountRows(con, name('books_copy'), []))[0],
            5
        );
        await con.query(
            `CREATE TABLE ${q(
                'serial_original'
            )}(id serial PRIMARY KEY, label text); INSERT INTO ${q(
                'serial_original'
            )}(label) VALUES ('first')`
        );
        assert.ifError(
            await admin.CloneTable(
                con,
                name('serial_original'),
                name('serial_copy'),
                true
            )
        );
        const sequences = await con.query(
            `SELECT pg_get_serial_sequence(?, 'id') original, pg_get_serial_sequence(?, 'id') copy`,
            {
                replacements: [q('serial_original'), q('serial_copy')],
                type: QueryTypes.SELECT,
            }
        );
        assert.notEqual(sequences[0].original, sequences[0].copy);
        assert.equal(
            (
                await con.query(
                    `INSERT INTO ${q(
                        'serial_copy'
                    )}(label) VALUES ('second') RETURNING id`,
                    { type: QueryTypes.SELECT }
                )
            )[0].id,
            2
        );
        assert.ifError(
            await admin.RenameTable(con, name('wizard'), name('renamed'))
        );
        assert.ifError(await admin.TruncateTable(con, name('renamed')));
        assert.ifError(await admin.DropTable(con, name('renamed')));
        console.log(
            'PostgreSQL integration passed: samples, metadata, filtered reads, writes, duplicates, conflicts, typed streaming, table editing and cloning.'
        );
    } finally {
        await con.query(`DROP SCHEMA "${schema}" CASCADE`);
        await con.close();
    }
})().catch((error) => {
    console.error(error);
    process.exitCode = 1;
});
