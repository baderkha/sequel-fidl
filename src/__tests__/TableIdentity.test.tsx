import '@testing-library/jest-dom';
import { act, fireEvent, render, screen } from '@testing-library/react';
import { api } from '../renderer/api';
import { CreateTableWizard } from '../renderer/Components/CreateTable/CreateTableWizard';
import { DialectContext } from '../renderer/database/DialectContext';
import {
    buildSQL,
    newTable,
    validate,
} from '../renderer/Components/CreateTable/model';
import {
    buildPostgresSQL,
    validatePostgres,
} from '../renderer/Components/CreateTable/postgres';

jest.mock('../renderer/api', () => ({
    api: { runQuery: jest.fn(), applySchemaChanges: jest.fn() },
}));
jest.mock('../renderer/Components/SqlEditor/SqlEditor', () => ({
    SqlEditor: ({ value }: { value: string }) => (
        <pre data-testid="sql-preview">{value}</pre>
    ),
}));

beforeEach(() => {
    jest.clearAllMocks();
    localStorage.clear();
    (api.runQuery as jest.Mock).mockResolvedValue([[], null]);
    (api.applySchemaChanges as jest.Mock).mockResolvedValue({});
});

it.each(['mysql', 'postgres'] as const)(
    'creates a valid default %s table with discoverable auto increment',
    async (dialect) => {
        render(
            <DialectContext.Provider value={dialect}>
                <CreateTableWizard
                    conID="connection-1"
                    tables={[]}
                    getSchema={jest.fn()}
                    onClose={jest.fn()}
                    onCreated={jest.fn()}
                />
            </DialectContext.Provider>
        );
        await act(async () => {
            await Promise.resolve();
        });
        fireEvent.change(screen.getByPlaceholderText('table_name'), {
            target: { value: 'people' },
        });
        const checkbox = screen.getByRole('checkbox', {
            name: 'Auto increment for id',
        });
        expect(checkbox).toBeEnabled();
        expect(checkbox).toBeChecked();
        expect(
            screen.getByRole('combobox', { name: 'Type for id' })
        ).toHaveValue(dialect === 'postgres' ? 'INTEGER' : 'INT');
        expect(
            screen.getByRole('checkbox', { name: 'Allow NULL for id' })
        ).toBeDisabled();
        expect(
            screen.getByText('Auto increment', { exact: true })
        ).toBeInTheDocument();
        const generated =
            dialect === 'postgres'
                ? 'GENERATED BY DEFAULT AS IDENTITY'
                : 'AUTO_INCREMENT';
        expect(screen.getByTestId('sql-preview')).toHaveTextContent(generated);
        fireEvent.click(checkbox);
        expect(screen.getByTestId('sql-preview')).not.toHaveTextContent(
            generated
        );
        fireEvent.click(checkbox);
        expect(screen.getByTestId('sql-preview')).toHaveTextContent(generated);
        if (dialect === 'postgres') {
            expect(
                screen.getByText(/backed by a PostgreSQL sequence/)
            ).toBeInTheDocument();
            expect(api.runQuery).not.toHaveBeenCalled();
        }
    }
);

it('uses the same correct identity defaults in the pure schema model and SQL preview', () => {
    const mysql = newTable('mysql');
    mysql.name = 'people';
    const postgres = newTable('postgres');
    postgres.name = 'people';
    expect(validate(mysql, [])).toEqual([]);
    expect(validatePostgres(postgres, [])).toEqual([]);
    expect(buildSQL(mysql)).toContain('AUTO_INCREMENT');
    expect(buildPostgresSQL(postgres)).toContain(
        '"id" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL'
    );
    expect(postgres.columns[0].unsigned).toBe(false);
});
